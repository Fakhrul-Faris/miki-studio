# EX34 → hf/: one Three.js world composition (build/world.src.html) + EX15 captions + grain + the mix
#   ~/.local/bin/uv run -q --offline --with pillow python build/hf_ex34.py
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import hfkit as h
EP, HF, END = h.EP, h.HF, h.END
FLOOR = "#22304C"

def build():
    os.makedirs(f"{HF}/compositions", exist_ok=True)
    for f in os.listdir(f"{HF}/compositions"): os.remove(f"{HF}/compositions/{f}")
    w = open(f"{EP}/build/world.src.html").read()
    w = w.replace("/*TIMES*/", json.dumps(h.W)).replace("/*END*/", f"{END}").replace("/*FONT3D*/", open(f"{HF}/assets/fonts3d/helvetiker_bold.typeface.json").read())
    files = {"world": w, **h.overlays()}
    for k, v in files.items(): open(f"{HF}/compositions/{k}.html", "w").write(v)
    layers = (("world", 1, "graphics", 1), ("grain", 8, "graphics", 20), ("caps", 9, "captions", 30))
    hosts = "\n".join(f'      <div id="{n}" data-composition-id="{n}" data-composition-src="compositions/{n}.html" data-start="0" data-duration="{END}" '
                      f'data-track-index="{ti}" data-track-kind="{kind}" data-width="1080" data-height="1920" style="z-index:{z}"></div>' for n, ti, kind, z in layers)
    audio = f'      <audio id="mix" class="clip" src="assets/mix.wav" data-start="0" data-duration="{END}" data-track-index="10" data-volume="1"></audio>' if os.path.exists(f"{HF}/assets/mix.wav") else ""
    open(f"{HF}/index.html", "w").write(f"""<!doctype html>
<html lang="en" data-resolution="portrait">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=1080, height=1920" />
    <script src="https://cdn.jsdelivr.net/npm/gsap@3.15.0/dist/gsap.min.js"></script>
    <script src="https://cdn.jsdelivr.net/npm/gsap@3.15.0/dist/CustomEase.min.js"></script>
    <script>gsap.registerPlugin(CustomEase);</script>
    <style>
      * {{ margin: 0; padding: 0; box-sizing: border-box; }}
      html, body {{ margin: 0; width: 1080px; height: 1920px; overflow: hidden; background: {FLOOR}; }}
      #root {{ position: relative; width: 1080px; height: 1920px; }}
    </style>
  </head>
  <body>
    <!-- EX34 · generated by build/hf_ex34.py — edit build/world.src.html and rebuild -->
    <div id="root" data-composition-id="main" data-start="0" data-duration="{END}" data-fps="60" data-width="1080" data-height="1920">
{hosts}
{audio}
    </div>
    <script>
      window.__timelines["main"] = gsap.timeline({{ paused: true }});
    </script>
  </body>
</html>
""")
    print("built world + caps + grain, end", END)

if __name__ == "__main__": build()
