#!/usr/bin/env python3
"""05_calendar/posting-plan.md: the manual posting reference (slots, files, captions, pinned comments), generated from each
episode's episode.md § Post so captions are never retyped. Edit ROWS for the schedule, then: python3 tools/posting_plan.py"""
import re
ROWS = [  # date, time, EX, folder, title, final, status
  ("Sun 8 Nov", "12:30", "EX24", "EX24_mcd-ice-cream", "The Machine Isn't Broken", "export/EX24-Final.mp4", "✅ ready"),
  ("Sun 8 Nov", "21:00", "EX25", "EX25_99speedmart", "How Is 99 Speedmart So Cheap? (Part 1)", "export/EX25-Final.mp4", "✅ ready"),
  ("Mon 9 Nov", "12:30", "EX26", "EX26_starbucks-float", "The Bank That Sells Coffee", "export/EX26-Final.mp4", "⏳ script approved, waiting for voice"),
  ("Mon 9 Nov", "21:00", "EX27", "EX27_1111-fake-discount", "The 10% Off That Costs More (Shopee 11.11)", "export/EX27-Final.mp4", "⏳ script v2 waiting for approval"),
]
def post(ep):
    s = open(f"04_episodes/{ep}/episode.md").read()
    cap = re.search(r"\*\*Caption:\*\*\s*```\n(.*?)```", s, re.S); pin = re.search(r"\*\*Pinned comment:\*\*\s*```\n(.*?)```", s, re.S)
    return (cap.group(1).strip() if cap else "(missing)"), (pin.group(1).strip() if pin else "(missing)")
out = ["# Posting plan (fallback while the Air is off)", "",
  "Manual reference for TikTok Studio, generated by `tools/posting_plan.py` from each episode's `episode.md` § Post (edit captions",
  "there, then rerun). When the Air is back on: push every ✅ final to Telegram (`tools/air.sh sync && tools/air.sh push-episode EXNN`)",
  "and mark posted ones with `/posted exNN` in the bot.", "",
  "## Before every post", "",
  "- Turn on the **AI-generated content** label.",
  "- Paste the caption exactly; post the pinned comment right after and pin it.",
  "- Reply to every comment in the first hour.",
  "- Post at the slot (12:30 quick / 21:00 main, MYT); one video per slot, no gaps.",
  "- 24 h later: screenshot the video's analytics (retention graph, traffic sources) into `06_analytics/`.", "",
  "## Schedule", "", "| Date | Time (MYT) | Episode | Title | File | Status |", "|---|---|---|---|---|---|"]
for d, t, n, ep, title, f, st in ROWS: out.append(f"| {d} | {t} | {n} | {title} | `04_episodes/{ep}/{f}` | {st} |")
out += ["", "Strategy and checkpoints (14 Nov ≥ 150 followers, 21 Nov ≥ 450, 30 Nov 1,000 + one 100k video): memory `tiktok-goal-nov-2026`.", ""]
for d, t, n, ep, title, f, st in ROWS:
    cap, pin = post(ep)
    out += [f"## {n} — {title}", "", f"**{d}, {t} MYT** · `04_episodes/{ep}/{f}` · {st}", "", "**Caption:**", "```", cap, "```", "**Pinned comment:**", "```", pin, "```", ""]
open("05_calendar/posting-plan.md", "w").write("\n".join(out)); print("05_calendar/posting-plan.md:", len(ROWS), "posts")
